alter table public.profiles
  add column if not exists preferred_store_id text,
  add column if not exists preferred_store_name text,
  add column if not exists preferred_store_address jsonb,
  add column if not exists stripe_customer_id text,
  add column if not exists stripe_subscription_id text;

create table if not exists public.households (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 2 and 80),
  invite_code text not null unique,
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.household_members (
  household_id uuid not null references public.households(id) on delete cascade,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  member_role text not null default 'member' check (member_role in ('owner','member')),
  joined_at timestamptz not null default now(),
  primary key (household_id,user_id)
);
create index if not exists household_members_user_idx on public.household_members(user_id);

create table if not exists public.recipe_ratings (
  id bigint generated by default as identity primary key,
  recipe_id text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  review text not null default '' check (char_length(review) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (recipe_id,user_id)
);
create index if not exists recipe_ratings_recipe_idx on public.recipe_ratings(recipe_id,created_at desc);

create table if not exists public.recipe_favorites (
  recipe_id text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (recipe_id,user_id)
);
create index if not exists recipe_favorites_recipe_idx on public.recipe_favorites(recipe_id);

alter table public.households enable row level security;
alter table public.household_members enable row level security;
alter table public.recipe_ratings enable row level security;
alter table public.recipe_favorites enable row level security;

revoke all on public.households, public.household_members, public.recipe_ratings, public.recipe_favorites from anon, authenticated;
grant select, insert, update, delete on public.households, public.household_members, public.recipe_ratings, public.recipe_favorites to service_role;
grant usage, select on all sequences in schema public to service_role;
