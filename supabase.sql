create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default 'Cook',
  email text not null,
  points integer not null default 0 check (points >= 0),
  taste_preferences jsonb not null default '[]'::jsonb,
  shopping_style text not null default 'value',
  tried_recipes jsonb not null default '[]'::jsonb,
  meals_cooked integer not null default 0 check (meals_cooked >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.reward_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  points integer not null,
  reference_id text,
  created_at timestamptz not null default now()
);

create index if not exists reward_events_user_id_idx on public.reward_events(user_id);

alter table public.profiles enable row level security;
alter table public.reward_events enable row level security;

-- The Vercel API uses the Supabase service role, so these tables are intentionally
-- not exposed to anonymous browser clients. If you later add direct Supabase
-- client access, add narrowly scoped RLS policies instead of opening the tables.

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_updated_at on public.profiles;
create trigger profiles_updated_at
before update on public.profiles
for each row execute function public.set_updated_at();

-- Optional: if you want Supabase to automatically create a profile after signup,
-- you can enable this trigger. The Vercel API already calls ensureProfile(), so
-- leaving it off avoids duplicate-row races during the first login.

alter table public.reward_events drop constraint if exists reward_events_user_action_reference_key;
alter table public.reward_events add constraint reward_events_user_action_reference_key unique (user_id, action, reference_id);

create or replace function public.award_reward(
  p_user_id uuid,
  p_action text,
  p_points integer,
  p_reference text
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  new_points integer;
begin
  if exists (
    select 1 from public.reward_events
    where user_id = p_user_id and action = p_action and reference_id = p_reference
  ) then
    select points into new_points from public.profiles where id = p_user_id;
    return coalesce(new_points, 0);
  end if;

  insert into public.reward_events(user_id, action, points, reference_id)
  values (p_user_id, p_action, p_points, p_reference);

  update public.profiles
  set points = points + p_points
  where id = p_user_id
  returning points into new_points;

  return coalesce(new_points, 0);
end;
$$;

revoke all on function public.award_reward(uuid, text, integer, text) from anon, authenticated;
grant execute on function public.award_reward(uuid, text, integer, text) to service_role;
