create table if not exists public.recipe_overrides (
  recipe_id text primary key,
  image_url text,
  video_url text,
  locked boolean not null default false,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.site_events (
  id bigint generated by default as identity primary key,
  event text not null,
  visitor_id text not null,
  path text,
  recipe_id text,
  created_at timestamptz not null default now()
);

create index if not exists site_events_created_at_idx on public.site_events(created_at);
create index if not exists site_events_visitor_id_idx on public.site_events(visitor_id);
create index if not exists site_events_event_idx on public.site_events(event);

create table if not exists public.pending_orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  recipe_id text not null,
  order_id text,
  status text not null default 'pending' check (status in ('pending','verified','rejected')),
  created_at timestamptz not null default now(),
  verified_at timestamptz,
  verified_by uuid references auth.users(id) on delete set null
);

create index if not exists pending_orders_status_idx on public.pending_orders(status);
create index if not exists pending_orders_user_id_idx on public.pending_orders(user_id);

create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  order_id text not null,
  amount numeric(12,2) not null default 0,
  currency text not null default 'USD',
  status text not null default 'completed',
  source text not null default 'manual',
  created_at timestamptz not null default now()
);

create index if not exists sales_created_at_idx on public.sales(created_at);
create index if not exists sales_status_idx on public.sales(status);

